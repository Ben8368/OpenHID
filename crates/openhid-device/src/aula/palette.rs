//! Wireless single-color palette reports for built-in AULA effects.
//!
//! The 37-report layout is adapted from the MIT-licensed Aula-Manager wireless
//! reference. The palette has no verified readback on the F87 PRO receiver.

use openhid_core::hid::aula::AulaRgb;

use super::{ConfigError, FRAME_LENGTH, checksum, transaction::send_and_await_echo};
use crate::backend::RawSession;

const PALETTE_FRAME_COUNT: usize = 37;

/// Build the full palette upload, optionally replacing palette slot zero.
#[must_use]
pub fn encode_wireless_palette_frames(
    color: Option<AulaRgb>,
) -> [[u8; FRAME_LENGTH]; PALETTE_FRAME_COUNT] {
    let mut frames = [[0; FRAME_LENGTH]; PALETTE_FRAME_COUNT];
    for (sequence, frame) in frames.iter_mut().enumerate() {
        frame[0] = 0x13;
        frame[1] = 0x09;
        frame[2] = 0x25;
        frame[3] = sequence.to_le_bytes()[0];

        let payload = if let Some(template) = PALETTE_TEMPLATE.get(sequence) {
            *template
        } else if sequence == PALETTE_FRAME_COUNT - 1 {
            PALETTE_TRAILER
        } else {
            PALETTE_ZERO
        };
        frame[4..19].copy_from_slice(&payload);

        if sequence == 1
            && let Some(color) = color
        {
            let [red, green, blue] = color.channels();
            frame[12] = red;
            frame[13] = green;
            frame[14] = blue;
            frame[16] = 0xff;
        }
        frame[19] = checksum(frame);
    }
    frames
}

pub(super) async fn write_palette(
    session: &mut dyn RawSession,
    color: Option<AulaRgb>,
    cancelled: &impl Fn() -> bool,
) -> Result<(), ConfigError> {
    for (sequence, frame) in encode_wireless_palette_frames(color).iter().enumerate() {
        if cancelled() {
            return Err(ConfigError::PalettePartial {
                completed_reports: u8::try_from(sequence).unwrap_or(u8::MAX),
                failed_sequence: u8::try_from(sequence).unwrap_or(u8::MAX),
                cause: Box::new(ConfigError::Cancelled),
            });
        }
        if let Err(cause) = send_and_await_echo(session, frame).await {
            return Err(ConfigError::PalettePartial {
                completed_reports: u8::try_from(sequence).unwrap_or(u8::MAX),
                failed_sequence: u8::try_from(sequence).unwrap_or(u8::MAX),
                cause: Box::new(cause),
            });
        }
    }
    Ok(())
}

